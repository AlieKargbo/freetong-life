import { Pool } from 'pg';

export interface PlayerRecord {
  id: number;
  username: string;
  display_name: string;
}

export interface LoginRecord {
  id: number;
  username: string;
  password_salt: string;
  password_hash: string;
}

export class DataServiceError extends Error {
  constructor(message: string, public readonly status: number) {
    super(message);
    this.name = 'DataServiceError';
  }
}

// Local development uses the PostgreSQL instance configured by DATABASE_URL.
// Production continues to use the authenticated Cloudflare D1 Worker API.
const localPool = process.env.NODE_ENV === 'development' && process.env.DATABASE_URL
  ? new Pool({ connectionString: process.env.DATABASE_URL, max: 5 })
  : null;
let localSchemaReady: Promise<void> | null = null;

async function ensureLocalSchema() {
  if (!localPool) return;
  if (!localSchemaReady) {
    localSchemaReady = localPool.query(`
      CREATE TABLE IF NOT EXISTS players (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        email TEXT UNIQUE,
        display_name TEXT NOT NULL,
        password_salt TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS player_sessions (
        token_hash TEXT PRIMARY KEY,
        player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS player_sessions_expiry_idx ON player_sessions (expires_at);
      CREATE TABLE IF NOT EXISTS player_saves (
        player_id BIGINT PRIMARY KEY REFERENCES players(id) ON DELETE CASCADE,
        data JSONB NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `).then(() => undefined).catch((error) => {
      localSchemaReady = null;
      throw error;
    });
  }
  await localSchemaReady;
}

async function callLocalDataService<T>(action: string, values: Record<string, unknown>): Promise<T> {
  if (!localPool) throw new Error('Local PostgreSQL is not configured.');
  await ensureLocalSchema();
  try {
    switch (action) {
      case 'create-player': {
        const { rows } = await localPool.query<{ id: string }>(
          'INSERT INTO players (username, email, display_name, password_salt, password_hash) VALUES ($1, $2, $3, $4, $5) RETURNING id',
          [values.username, values.email, values.displayName, values.passwordSalt, values.passwordHash],
        );
        return { id: Number(rows[0].id) } as T;
      }
      case 'find-player': {
        const { rows } = await localPool.query<Omit<LoginRecord, 'id'> & { id: string }>(
          'SELECT id, username, password_salt, password_hash FROM players WHERE username = $1 OR email = $2 LIMIT 1',
          [values.username, values.email],
        );
        return { player: rows[0] ? { ...rows[0], id: Number(rows[0].id) } : null } as T;
      }
      case 'create-session':
        await localPool.query(
          'INSERT INTO player_sessions (token_hash, player_id, expires_at) VALUES ($1, $2, $3)',
          [values.tokenHash, values.playerId, new Date(Number(values.expiresAt))],
        );
        return { ok: true } as T;
      case 'find-session': {
        const { rows } = await localPool.query<Omit<PlayerRecord, 'id'> & { id: string }>(
          `SELECT p.id, p.username, p.display_name FROM player_sessions s
           JOIN players p ON p.id = s.player_id WHERE s.token_hash = $1 AND s.expires_at > $2`,
          [values.tokenHash, new Date(Number(values.now))],
        );
        return { player: rows[0] ? { ...rows[0], id: Number(rows[0].id) } : null } as T;
      }
      case 'delete-session':
        await localPool.query('DELETE FROM player_sessions WHERE token_hash = $1', [values.tokenHash]);
        return { ok: true } as T;
      case 'get-save': {
        const { rows } = await localPool.query<{ data: unknown }>(
          'SELECT data FROM player_saves WHERE player_id = $1', [values.playerId],
        );
        return { save: rows[0]?.data ?? null } as T;
      }
      case 'put-save':
        await localPool.query(
          `INSERT INTO player_saves (player_id, data, updated_at) VALUES ($1, $2::jsonb, $3)
           ON CONFLICT (player_id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at`,
          [values.playerId, JSON.stringify(values.save), new Date()],
        );
        return { ok: true } as T;
      default:
        throw new Error(`Unsupported local database action: ${action}`);
    }
  } catch (error) {
    if ((error as { code?: string })?.code === '23505') {
      throw new DataServiceError('Account already exists.', 409);
    }
    throw error;
  }
}

async function callDataService<T>(action: string, values: Record<string, unknown> = {}): Promise<T> {
  if (localPool) return callLocalDataService<T>(action, values);
  const baseUrl = process.env.CLOUDFLARE_API_URL;
  const token = process.env.CLOUDFLARE_API_TOKEN;
  if (!baseUrl || !token) throw new Error('Cloudflare data service is not configured.');

  const endpoint = new URL('/_internal/db', baseUrl);
  const response = await fetch(endpoint, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ action, ...values }),
    signal: AbortSignal.timeout(10_000),
    cache: 'no-store',
  });

  const result = await response.json().catch(() => ({})) as { error?: unknown } & T;
  if (!response.ok) {
    const message = typeof result.error === 'string' ? result.error : 'Cloudflare data service request failed.';
    throw new DataServiceError(message, response.status);
  }
  return result;
}

export function createPlayer(input: {
  username: string;
  email: string | null;
  displayName: string;
  passwordSalt: string;
  passwordHash: string;
}) {
  return callDataService<{ id: number }>('create-player', input);
}

export function findPlayerForLogin(username: string, email: string) {
  return callDataService<{ player: LoginRecord | null }>('find-player', { username, email })
    .then(({ player }) => player);
}

export function insertSession(playerId: number, tokenHash: string, expiresAt: number) {
  return callDataService<{ ok: true }>('create-session', { playerId, tokenHash, expiresAt });
}

export function findPlayerBySession(tokenHash: string, now: number) {
  return callDataService<{ player: PlayerRecord | null }>('find-session', { tokenHash, now })
    .then(({ player }) => player);
}

export function deleteSession(tokenHash: string) {
  return callDataService<{ ok: true }>('delete-session', { tokenHash });
}

export function getPlayerSave(playerId: number) {
  return callDataService<{ save: unknown | null }>('get-save', { playerId })
    .then(({ save }) => save);
}

export function putPlayerSave(playerId: number, save: unknown) {
  return callDataService<{ ok: true }>('put-save', { playerId, save });
}
